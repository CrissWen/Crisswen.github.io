// ===== Цитати дня для футера =====
// Один спільний список для ВСІХ тем (тон — темний гумор). Цитата обирається за номером дня в році
// за локальною датою гравця: увесь день вона та сама, а наступного дня йде наступна по колу.
// Коли цитати закінчуються (або настає 366-й день високосного року), відлік іде спочатку.
//
// Зараз тут заглушки. Щоб наповнити справжніми цитатами, замініть stubQuotes() на свій масив:
//   export const FOOTER_QUOTES = [
//     'Повітря в бункері закінчується. Але ви тримайтесь.',
//     ... (365 рядків)
//   ];
// Якщо масив порожній — покажеться FALLBACK_QUOTE.

export const QUOTES_COUNT = 365;

export const FALLBACK_QUOTE = 'Повітря в бункері закінчується. Але ви тримайтесь.';

function stubQuotes() {
  return Array.from({ length: QUOTES_COUNT }, (_, i) => `Цитата дня №${i + 1}`);
}

export const FOOTER_QUOTES = stubQuotes();
